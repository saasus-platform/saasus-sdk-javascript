const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const { version } = require(path.join(root, "package.json"));
const lockfile = require(path.join(root, "package-lock.json"));
const versionFile = path.join(root, "VERSION");
const sourceFile = path.join(root, "src/sdk-version.ts");
const versionContent = `${version}\n`;
const sourceContent = `// Code generated by scripts/update-version.cjs. Do not edit.\nexport const SDK_VERSION = ${JSON.stringify(version)};\n`;
const [mode, tag, ...extra] = process.argv.slice(2);

if (extra.length || (mode !== undefined && mode !== "--check")) {
  throw new Error("Usage: node scripts/update-version.cjs [--check [tag]]");
}
if (lockfile.version !== version || lockfile.packages[""].version !== version) {
  throw new Error("package-lock.json does not match package.json");
}

if (mode === "--check") {
  if (tag !== undefined && tag.replace(/^v/, "") !== version) {
    throw new Error(`Release tag ${tag} does not match package.json (${version})`);
  }
  if (fs.readFileSync(versionFile, "utf8") !== versionContent ||
      fs.readFileSync(sourceFile, "utf8") !== sourceContent) {
    throw new Error(`VERSION or SDK source does not match package.json (${version})`);
  }
} else {
  fs.writeFileSync(versionFile, versionContent);
  fs.writeFileSync(sourceFile, sourceContent);
}
